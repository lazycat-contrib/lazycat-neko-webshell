import { readFileSync, readdirSync, existsSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

export function discoverPlugins(root) {
  const directory = resolve(root, "src/plugins");
  const ids = new Set();
  const plugins = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const path = resolve(directory, entry.name, "plugin.json");
    if (!existsSync(path)) continue;
    const plugin = JSON.parse(readFileSync(path, "utf8"));
    if (!/^[a-z][a-z0-9-]*$/.test(plugin.id) || ids.has(plugin.id)) throw new Error(`Invalid or duplicate plugin id: ${plugin.id}`);
    ids.add(plugin.id);
    if (!existsSync(resolve(directory, entry.name, "mod.rs"))) throw new Error(`Missing native entry: ${plugin.id}`);
    if (typeof plugin.frontend?.entry !== "string" || plugin.frontend.entry.includes("..") || !existsSync(resolve(root, "src/frontend/src/plugins", plugin.frontend.entry))) throw new Error(`Missing frontend entry: ${plugin.id}`);
    if (!Array.isArray(plugin.resources) || plugin.resources.some((resource) => typeof resource !== "string")) throw new Error(`Missing resource contract: ${plugin.id}`);
    if (plugin.configuration?.version !== 1 || typeof plugin.configuration.metadata !== "object") throw new Error(`Missing configuration contract: ${plugin.id}`);
    if (typeof plugin.enabled !== "boolean" || typeof plugin.metadata !== "object") throw new Error(`Missing configuration defaults: ${plugin.id}`);
    if (plugin.metadata.ngrokAuthtoken || plugin.metadata.aiApiKey) throw new Error(`Secret in plugin manifest: ${plugin.id}`);
    plugins.push(plugin);
  }
  if (!plugins.length) throw new Error("No built-in plugins discovered");
  return plugins.sort((a, b) => a.id.localeCompare(b.id, "en"));
}

export function generatedCatalog(plugins) {
  const header = "// Generated by scripts/plugin-catalog.mjs from plugin.json.\n// Run npm run plugins:generate after editing plugin manifests.\n";
  const data = plugins.map(({ id, frontend, resources, configuration }) => ({ id, frontend, resources, configuration }));
  let catalog = `${header}export const BUILTIN_PLUGINS = ${JSON.stringify(data, null, 2)} as const;\n\n`;
  catalog += `export const PLUGIN_IDS = ${JSON.stringify(Object.fromEntries(plugins.map(({ id }) => [id.replaceAll("-", "_").toUpperCase(), id])), null, 2)} as const;\n`;
  let entries = `${header}import type { PluginDescriptor } from "../gen/lazycat/webshell/v1/capability_pb";\nimport type { PluginSettingsViewState } from "../plugin-views";\nimport type { PluginEntry } from "./host";\n`;
  for (const plugin of plugins) {
    const variable = plugin.id.replaceAll("-", "_");
    entries += `import { createEntry as ${variable}, renderSettings as ${variable}Settings, isSettingsOpen as ${variable}SettingsOpen, type EntryResources as ${variable}Resources } from "./${plugin.frontend.entry}";\n`;
  }
  entries += "\nexport type BuiltinPluginResources = {\n";
  for (const plugin of plugins) entries += `  "${plugin.id}": ${plugin.id.replaceAll("-", "_")}Resources;\n`;
  entries += "};\n\nexport function createBuiltinPluginEntries(resources: BuiltinPluginResources): Map<string, PluginEntry> {\n  const entries: PluginEntry[] = [\n";
  for (const plugin of plugins) entries += `    ${plugin.id.replaceAll("-", "_")}(resources["${plugin.id}"]),\n`;
  entries += "  ];\n  return new Map(entries.map((entry) => [entry.id, entry]));\n}\n\n";
  entries += "export const pluginSettings: Record<string, { render: (plugin: PluginDescriptor, state: PluginSettingsViewState) => string; open: (state: PluginSettingsViewState) => boolean }> = {\n";
  for (const plugin of plugins) entries += `  "${plugin.id}": { render: ${plugin.id.replaceAll("-", "_")}Settings, open: ${plugin.id.replaceAll("-", "_")}SettingsOpen },\n`;
  entries += "};\n";
  return new Map([["catalog.generated.ts", catalog], ["entries.generated.ts", entries]]);
}

export function updateCatalog(root, check = false) {
  const files = generatedCatalog(discoverPlugins(root));
  for (const [name, source] of files) {
    const path = resolve(root, "src/frontend/src/plugins", name);
    if (existsSync(path) && readFileSync(path, "utf8") === source) continue;
    if (check) throw new Error(`Plugin catalog is stale: ${name}; run npm run plugins:generate`);
    writeFileSync(path, source);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  updateCatalog(root, process.argv.includes("--check"));
}
